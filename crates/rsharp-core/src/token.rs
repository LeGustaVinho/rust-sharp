use crate::error::Span;

/// Segment inside an interpolated string literal `$"Hello {name:fmt}"`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum InterpPart {
    Literal(String),
    Expr {
        source: String,
        format: Option<String>,
    },
}

