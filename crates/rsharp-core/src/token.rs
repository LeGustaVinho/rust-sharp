/// Token kinds emitted by the R# lexer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TokenKind {
    Kw(Keyword),
    /// Standard identifier (including verbatim `@ident` with leading `@` stripped and `verbatim = true`).
    Ident {
        name: String,
        verbatim: bool,
    },
    IntLit(String),
    FloatLit(String),
    StringLit(String),
    RawStringLit(String),
    ByteLit(String),
    ByteStringLit {
        value: String,
        raw: bool,
    },
    CStringLit {
        value: String,
        raw: bool,
    },
    CharLit(String),
    InterpString(Vec<InterpPart>),
    DocComment(String),
    InnerDocComment(String),
    Shebang(String),
    /// Verbatim inline `rust { ... }` block payload.
    RustBlock(String),
    // Punctuation & operators
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Semicolon,
    Colon,
    ColonColon,
    Dot,
    DotDot,
    DotDotEq,
    DotDotDot,
    Question,
    QuestionQuestion,
    FatArrow,
    ThinArrow,
    Plus,
    PlusPlus,
    PlusEq,
    Minus,
    MinusMinus,
    MinusEq,
    Star,
    StarEq,
    Slash,
    SlashEq,
    Percent,
    PercentEq,
    Eq,
    EqEq,
    Bang,
    BangEq,
    Lt,
    Le,
    Gt,
    Ge,
    Amp,
    AmpAmp,
    AmpEq,
    Pipe,
    PipePipe,
    PipeEq,
    Caret,
    CaretEq,
    Tilde,
    Shl,
    ShlEq,
    Shr,
    ShrEq,
    Dollar,
    Hash,
    Eof,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

impl Token {
    pub const fn new(kind: TokenKind, span: Span) -> Self {
        Self { kind, span }
    }
}
